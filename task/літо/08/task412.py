# Напишіть програму, яка роздруковує лише ті елементи введеного списку, що менше
# введеного значення n. Список містить унікальні значення.
# Вхідні дані:
# 2 7 11 3 8 90 144 15 5 94
# Вихідні дані:
# 2 7 11 3 8 90 15 5
numbers = list(map(int, input("Введіть числа: ").split()))
n = int(input("Введіть n: "))
for num in numbers:
    if num < n:
        print(num, end=" ")



