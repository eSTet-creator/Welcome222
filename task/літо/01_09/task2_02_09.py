# Створіть масив із цінами (наприклад: [100, 450, 800, 1200, 300, 1500]).
# Програма перебирає цей масив і для кожної ціни перевіряє:
# Якщо ціна більша за 500 — виводить: Ціна [X] грн — Дорого (потрібна знижка!).
# Якщо ціна 500 або менша — виводить: Ціна [X] грн — Чудова ціна!.
numbers = [120, 480, 845, 500, 1250, 380, 1800]
for n in numbers:
    if n > 500:
        print(f"Ціна {n} грн - Дорого (потрібна знижка!)")
    else:
        print(f"Ціна {n} грн - Чудова ціна!")
