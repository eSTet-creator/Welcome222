# Програма просить користувача ввести своє ім'я або пароль.
# Якщо користувач ввів слово "Admin":
# Програма виводить: Доступ дозволено! Ласкаво просимо.
# У всіх інших випадках (якщо ввели будь-яке інше ім'я):
# Програма виводить: Привіт, [Введене_Ім'я]! У вас звичайний доступ.
correct_name = "Admin"
name = input("enter your name: ")
if name == correct_name:
    print("Доступ дозволено! Ласкаво просимо")
else:
    print(f"Привіт, {name}!  У Вас звичайний доступ!")

