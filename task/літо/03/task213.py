# Введення вхідного значення n
n = int(input("Введіть n: "))
# Створення рядків (зовнішній цикл)
for i in range(n):
    # Кожен рядок починається з першого символу '#'
    print("#", end="")
     # Розраховуємо і друкуємо кількість пробілів (внутрішній цикл)
     # Кількість пробілів дорівнює i * 2
    for j in range(i * 2):
        print(" ", end="")
        #кожен рядок закінчується друком символу #
    print("#")






