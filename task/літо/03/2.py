# введення вхідного значення n
n = int(input("Введіть n: "))
# робимо цикл від 0 до n-1
for i in range(n):
   # Друкуємо сформовані рядки, де кількість пробілів дорівнює i*2
    print("#" + " " * (i * 2) + "#")
   # Значок * для рядків означає повторення (дублювання).
   # Значок + між рядками виконує конкатенацію (зшиває їх до купи в один текст).

