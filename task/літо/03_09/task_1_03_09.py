# Програма Запитує у користувача суму чека в ресторані (наприклад, 400).
# Запитує відсоток чайових, який він хоче залишити (наприклад, 10).
# Розраховує підсумкові числа та виводить у консоль:
# Сума чайових: [X] грн.
# Загальна сума до сплати: [Y] грн.

check = int(input("Введіть суму чека: "))
gratuity = int(input("Введіть відсоток чайових: "))
x = check / 100 * gratuity
y = check + x
print(f"Сума чайових: {x} \nЗагальна сума до сплати: {y}")











