# Просить користувача вигадати та ввести пароль.
# Перевіряє довжину введеного рядка:
# Якщо в паролі менше 8 символів — виводить: Пароль занадто короткий! Мінімум 8 символів..
# Якщо 8 або більше символів — виводить: Надійний пароль! Реєстрація успішна.


password = input(f"Введіть пароль: ")
if len(password) < 8:
    print(f"Пароль занадто короткий! Мінімум 8 символів.")
else:
    print(f"Надійний пароль! Реєстрація успішна.")



