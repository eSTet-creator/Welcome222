# Створіть список на основі введеної послідовності цілих чисел і надрукуйте його елементи таким чином: два останні елементи переміщені з кінця в початок списку без зміни їх початкового порядку.
# Вхідні дані:
#  4 10 2 9 4 7 3
# Вихідні дані:
#  7 3 4 10 2 9 4
nums = list(map(int, input("Введіть список чисел через пробіл: ").split()))

# Цикл виконається два рази: спочатку коли i = 0, потім коли i = 1
for i in range(2):
    last_num = nums.pop()  # Забираємо елемент з кінця
    nums.insert(0, last_num)  # Вставляємо в початок

    # Додатково виведемо проміжний результат, щоб побачити роботу змінної i
    print(f"Крок {i + 1}: перенесли число {last_num}, тепер список: {nums}")

print("\nОстаточний результат:")
print(*(nums))