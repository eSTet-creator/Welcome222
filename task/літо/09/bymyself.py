# 1.EXCHANGE SORT
def exchange_sort(arr):
    ops = 0 # Ініціалізуємо лічильник операцій порівняння
    n = len(arr) # Визначаємо довжину масиву
# Зовнішній цикл: проходимо по кожному елементу масиву крім останнього
    for i in range(n):
# Внутрішній цикл: шукаємо елементи після поточного 'i' для порівняння
        for j in range(i + 1, n):
            ops += 1 # Збільшуємо лічильник операцій на 1 перед кожним порівнянням
            if arr[i] > arr[j]:
                arr[i], arr[j] = arr[j], arr[i]
    return ops # Повертаємо загальну кількість виконаних операцій

# 2. BUBBLE SORT
def bubble_sort(arr):
    ops = 0
    n = len(arr)
# Зовнішній цикл: повторюємо процес проходження по масиву n разів
    for i in range(n):
        swapped = False # Прапорець для перевірки чи відбувались перестановки під час цього проходу
# Внутрішній цикл: Порівнюємо сусідні елементи (зменшуємо межу пошуку на 'i', бо найбільші елементи вже в кінці)
        for j in range(0, n - i - 1):
            ops += 1 # Збільшуємо лічильник операцій перед порівнянням сусідів
            # Якщо поточний сусід більше за наступного
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swapped = True # Встановлюємо прапорець, що відбулася перестановка
        # Якщо за весь прохід жодної перестановки не відбулося (масив вже відсортований)
        if not swapped:
            break # Достроково завершуємо роботу алгоритму для економії часу
    return ops # Повертаємо загальну кількість виконаних операцій порівняння

# 3. SELECTION SORT
def selection_sort(arr):
    ops = 0
    n = len(arr)
    # Зовнішній цикл: рухаємо межу невідсортованої частини масиву зліва направо
    for i in range(n):
        min_idx = i # Припускаємо, що перший елемент невідсортованоі частини є найменшим
        # Внутрішній цикл: шукаємо справжній мінімальний елемент серед решти невідсортованих чисел
        for j in range(i + 1, n):
            ops += 1
            # Якщо знаходимо елемент, який менший за поточний мінімум
            if arr[j] < arr[min_idx]:
                min_idx = j # Запамʼятовуємо індекс нового знайденого мінімального елемента
        # Після завершення внутрішнього циклу міняємо знайдений мінімум з першим невідсортованим елементом
        arr [i], arr[min_idx] = arr[min_idx], arr[i]
    return ops # Повертаємо кількість виконаних операцій порівняння

# 4. INSERTION SORT
def insertion_sort(arr):
    ops = 0
    n = len(arr)
    # Зовнішній цикл: починаємо з другого елементу (індекс 1) до кінця масиву
    for i in range(1, n):
        key = arr[i] # Зберігаємо елемент, який будемо вставляти у відсортовану частину
        j = i - 1 # Починаємо порівняння з елементом безпосередньо ліворуч від  key
        # Внутрішній цикл: рухаємось вліво поки не знайдемо правильне місце для key або не дійдемо до початку масиву
        while j >= 0:
            ops += 1
            # Якщо елемент ліворуч більший за key
            if arr[j] > key:
                arr[j + 1] = arr[j] # Зсуваємо більший елемент на одну позицію праворуч
                j -= 1 # Переходимо до наступного елементу ліворуч
            else:
                break # Якщо елемент зліва менший або рівний key, зупиняємо рух - місце знайдено
        arr[j + 1] = key # Вставляємо наш збережений елемент key у звільнену позицію
    return ops

# 5. QUICK SORT обгортка для запуску рекурсії
def quick_sort_run(arr):
    ops = [0] # Використовуємо список з одного елементу, щоб передавати лічильник операцій за посиланням у рекурсію
    # Внутрішня рекурсівна функція сортування меж від l ліва до r права
    def quick_sort(l, r):
        # Якщо межі не перетнулися і є що сортувати
        if l < r:
            # Розбиваємо масив навколо опорного елементу та отримуємо його фінальний індекс
            pivot_idx = partition(l, r)
            # Рекурсивно сортуємо ліву частину масиву від опорного елементу
            quick_sort(l, pivot_idx - 1)
            # Рекурсивно сортуємо праву частину масиву від опорного елементу
            quick_sort(pivot_idx + 1, r)

    # Функція розділення масиву (використовує схему Ломуто)
    def partition(l, r):
        pivot = arr[r] # Обираємо крайній правий елемент як опорний (pivot)
        i = l - 1 # Індекс елементу, що є межею менших за опорний чисел
        # Проходимо від лівоі межі l до передостаннього елемента r-1
        for j in range(l, r):
            ops[0] += 1 # Збільшуємо лічильник порівнянь з опорним елементом
            # Якщо поточний елемент менший за опорний
            if arr[j] < pivot:
                i += 1 # Зсуваємо межу менших елементів праворуч
                arr[i], arr[j] = arr[j], arr[i] # Міняємо поточний елемент місцями з елементом на межі
        # Переносимо сам опорний елемент (з кінця масиву) на його законне місце посередині
            arr[i + 1], arr[r] = arr[r], arr[i + 1]
        # Повертаємо індекс опорного елемента, навколо якого відбувся розподіл
        return i + 1
    quick_sort(0, len(arr) - 1) # Запускаємо рекурсивне сортування для всього масиву
    return ops[0]  # Повертаємо накопичену кількість порівнянь

