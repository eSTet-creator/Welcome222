# Для списку цілих чисел знайдіть і надрукуйте елементи, які зʼявляються у списку лише
# один раз.Елементи повинні бути роздруковані у тому порядку, в якому вони перебувають у вхідному списку.
# Вхідні дані:
# 5 3 1 6 5 8 0 12
# 1 45 23 45 90 1 0
# Вихідні дані:
# 3 1 6 8 0 12
# 23 90 0

print(
    "Введіть рядки з числами (для закінчення просто натисніть Enter на порожньому рядку):"
)

while True:
    line = input()

    # Якщо рядок порожній — виходимо з нескінченного циклу while, і програма завершується
    if not line.strip():
        break

    # Розбиваємо рядок на список окремих елементів
    numbers = line.split()

    # Створюємо порожній список, куди будемо додавати знайдені унікальні числа
    result = []

    # Класичний цикл for для перебору кожного числа
    for num in numbers:
        # Перевіряємо: якщо число зустрічається у списку numbers рівно 1 раз
        if numbers.count(num) == 1:
            # Додаємо це число в наш список-результат
            result.append(num)

    # Збираємо елементи списку назад у рядок через пробіл і виводимо
    print(" ".join(result))

print("Програму завершено!")